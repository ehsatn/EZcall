package app.ezcall.receiver

import android.content.Context

private const val unconfirmedSms = " Check the sending phone before retrying the unconfirmed SMS."

internal fun Context.receiverNotice(notice: String): String = when (notice) {
    "Allow Send SMS from the receiving phone in ezcall on Android." -> getString(R.string.r_sms_needs_permission)
    "Allow call control in ezcall on Android." -> getString(R.string.r_call_control_needed)
    "Android could not confirm the SMS. Check Android before retrying." -> getString(R.string.r_sms_check_sender)
    "Android could not send the SMS. Check the SIM and permissions." -> getString(R.string.r_sms_sim_error)
    "Android couldn't answer the call. You can still answer on Android if it's ringing." -> getString(R.string.r_answer_failed)
    "Android couldn't place the call." -> getString(R.string.r_dial_failed)
    "Answering on the sending phone…" -> getString(R.string.r_answering)
    "Audio stopped. Continue the call on the sending phone." -> getString(R.string.r_audio_interrupted)
    "Android couldn't move call audio to the receiving phone. Use the sending phone.",
    "Android stopped capturing call audio.",
    "Android stopped receiving call audio.",
    "Call audio stopped on Android." -> getString(R.string.r_audio_interrupted)
    "Android couldn't start the Opus codec." -> getString(R.string.r_audio_codec_failed)
    "Call audio isn't running on Android. Set it up in ezcall on Android." -> getString(R.string.r_audio_setup_needed)
    "Bluetooth disconnected. Reconnecting…" -> getString(R.string.r_reconnecting)
    "Bluetooth scan failed. Trying again." -> getString(R.string.r_scan_failed)
    "Call audio is on the sending phone." -> getString(R.string.r_audio_sender)
    "Call audio is on this phone." -> getString(R.string.r_audio_receiver)
    "Call audio returned to the sending phone." -> getString(R.string.r_audio_returned)
    "Call connected." -> getString(R.string.r_call_connected)
    "Call ended." -> getString(R.string.r_call_ended)
    "Call reconnected." -> getString(R.string.r_call_reconnect)
    "Call status was not confirmed. Check the sending phone." -> getString(R.string.r_call_unconfirmed)
    "Check the sending phone before retrying the unconfirmed SMS." -> getString(R.string.r_sms_uncertain_suffix)
    "Connected over Bluetooth" -> getString(R.string.r_bt_connected)
    "Connected over Bluetooth." -> getString(R.string.r_bt_confirm)
    "Connecting to the sending phone…" -> getString(R.string.r_connecting)
    "Connection test passed." -> getString(R.string.ez_test_passed)
    "Could not establish a secure Bluetooth link. Check the pairing code and try again." -> getString(R.string.r_secure_failed)
    "Could not remove the saved link. Try again." -> getString(R.string.r_forget_failed)
    "Could not save relayed data on this phone." -> getString(R.string.r_save_failed)
    "Could not save the sync. Try again." -> getString(R.string.r_sync_save_failed)
    "Dialing from the sending phone…" -> getString(R.string.r_dialing)
    "Ending the call…" -> getString(R.string.r_ending)
    "Enter a phone number and a message of up to 1,024 UTF-8 bytes." -> getString(R.string.r_send_validation)
    "Enter a phone number and a shorter message." -> getString(R.string.r_sms_shorter)
    "Enter a valid phone number." -> getString(R.string.r_invalid_number)
    "Finish the current call on Android first." -> getString(R.string.r_finish_other_call)
    "Incoming call" -> getString(R.string.r_call_incoming)
    "Incoming calls" -> getString(R.string.r_channel_calls)
    "Incoming messages" -> getString(R.string.r_channel_messages)
    "Listening on this phone. Speak into the sending phone." -> getString(R.string.r_audio_listen)
    "Looking for the sending phone…" -> getString(R.string.r_searching)
    "Messages and contacts are up to date." -> getString(R.string.r_synced)
    "New relayed message" -> getString(R.string.r_new_relayed)
    "No SMS confirmation received. Check the sending phone before retrying." -> getString(R.string.r_send_unconfirmed)
    "Open ezcall to read it." -> getString(R.string.r_open_message_alert)
    "Open ezcall to view the call." -> getString(R.string.r_open_call_alert)
    "Pairing removed." -> getString(R.string.r_pair_removed)
    "Pairing timed out. Show a new QR code on the sending phone and scan again." -> getString(R.string.r_pair_timeout)
    "Receiver connection" -> getString(R.string.r_channel_link)
    "SMS sent." -> getString(R.string.r_sent)
    "Securing the Bluetooth link…" -> getString(R.string.r_securing)
    "Sending SMS…" -> getString(R.string.r_sending)
    "Some or all of the SMS could not be sent. Check Android before retrying." -> getString(R.string.r_sms_some_unsent)
    "Sync could not finish. Try again." -> getString(R.string.r_sync_peer_failed)
    "Sync failed. Try again." -> getString(R.string.r_sync_failed)
    "Sync timed out. Try again." -> getString(R.string.r_sync_timeout)
    "Syncing messages and contacts…" -> getString(R.string.r_sync_progress)
    "Testing the connection…" -> getString(R.string.r_test_progress)
    "That number can't be dialed." -> getString(R.string.r_cant_dial)
    "The Bluetooth write timed out." -> getString(R.string.r_bt_timeout)
    "The call is no longer available on the receiving phone." -> getString(R.string.r_call_gone)
    "The call is no longer ringing." -> getString(R.string.r_ringing_ended)
    "The relay did not respond." -> getString(R.string.r_relay_no_response)
    "The saved pairing cannot be opened. Forget it and scan a fresh code." -> getString(R.string.r_open_pair_failed)
    "The sending phone could not complete the call action." -> getString(R.string.r_call_action_failed)
    "The sending phone could not send this SMS." -> getString(R.string.r_send_failed)
    "The sending phone did not answer the test." -> getString(R.string.r_test_failed)
    "The sending phone removed this link." -> getString(R.string.r_sender_unpaired)
    "This SMS is too long to send." -> getString(R.string.r_sms_too_long)
    "Turn on Bluetooth to receive calls and messages." -> getString(R.string.r_bt_off)
    "Wait for Android to finish sending the previous SMS." -> getString(R.string.r_sms_previous)
    "Waiting for the sending phone" -> getString(R.string.r_wait_sender)
    else -> if (notice.endsWith(unconfirmedSms)) {
        receiverNotice(notice.removeSuffix(unconfirmedSms)) + " " + getString(R.string.r_sms_uncertain_suffix)
    } else notice
}
